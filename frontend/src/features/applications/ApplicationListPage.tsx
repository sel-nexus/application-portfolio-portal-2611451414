/** Browse stored applications with shareable filters and audited CSV downloads. */
import { useState } from 'react';
import { Link, Navigate, useLocation, useSearchParams } from 'react-router-dom';
import { SESSION_EXPIRED, TOKEN_KEY } from '../../api';
import { DataTable } from '../../components/DataTable';
import { Field } from '../../components/Field';
import { useResource } from '../../useResource';
import { useAuth } from '../identity/AuthContext';
import type { ApplicationDetail, ApplicationPage } from '../../types';

/** Match worded status colors to the supplied enterprise visual system. */
export function applicationChip(value: string, category: 'risk' | 'criticality' | 'lifecycle') {
  const colors: Record<string, string> = {
    'risk:Low': 'bg-status-success text-on-primary', 'risk:Medium': 'bg-status-warning text-on-surface',
    'risk:High': 'bg-error text-on-error', 'criticality:High': 'bg-status-warning text-on-surface',
    'criticality:Critical': 'bg-error text-on-error', 'criticality:Medium': 'bg-status-info text-on-primary',
    'lifecycle:Active': 'bg-status-success text-on-primary',
  };
  return <span role="status" className={`chip ${colors[`${category}:${value}`] ?? 'bg-surface-variant text-on-surface'}`}>{value}</span>;
}

/** Render scope-safe choices and request precisely the current matching export. */
export default function ApplicationListPage() {
  const { user } = useAuth();
  const [params, setParams] = useSearchParams();
  const location = useLocation();
  const resource = useResource<ApplicationPage>(`/applications?${params}`);
  const [pending, setPending] = useState(false);
  const [error, setError] = useState('');
  /** Reset pagination when filters change, keeping remaining filters in the URL. */
  function filter(key: string, value: string) {
    const next = new URLSearchParams(params);
    if (value) next.set(key, value); else next.delete(key);
    next.delete('page'); setParams(next);
  }
  /** Download server-generated bytes and surface authentication and network failures. */
  async function download() {
    if (pending) return;
    setPending(true); setError('');
    try {
      const query = new URLSearchParams(params);
      query.delete('page'); query.delete('page_size');
      const base = (import.meta.env.VITE_API_BASE_URL ?? '').replace(/\/$/, '');
      const response = await fetch(`${base}/api/v1/applications/csv?${query}`, {
        headers: { Authorization: `Bearer ${localStorage.getItem(TOKEN_KEY) ?? ''}` }, cache: 'no-store',
      });
      if (!response.ok) {
        if (response.status === 401) {
          localStorage.removeItem(TOKEN_KEY); window.dispatchEvent(new Event(SESSION_EXPIRED));
        }
        const body = await response.json();
        throw new Error(typeof body.detail === 'string' ? body.detail : 'Unable to download CSV.');
      }
      const url = URL.createObjectURL(await response.blob());
      const anchor = document.createElement('a');
      anchor.href = url; anchor.download = 'applications.csv'; anchor.click(); URL.revokeObjectURL(url);
    } catch (reason) { setError(reason instanceof Error ? reason.message : 'Unable to download CSV.'); }
    finally { setPending(false); }
  }
  if (user?.mustChangePassword) return <Navigate to="/profile" replace />;
  if (!user?.permissions.includes('view')) return <p role="alert">You do not have permission for this action.</p>;
  const canCreate = user.permissions.includes('create') && ['Administrator', 'Portfolio Leader', 'Engineer'].includes(user.role);
  const columns = [
    { label: 'Name', render: (row: ApplicationDetail) => <Link to={`/applications/${row.id}`}>{row.name}</Link> },
    { label: 'Portfolio', render: (row: ApplicationDetail) => <Link to={`/portfolios/${row.portfolioId}`}>{row.portfolio}</Link> },
    { label: 'Criticality', render: (row: ApplicationDetail) => applicationChip(row.criticality, 'criticality') },
    { label: 'Tier', numeric: true, render: (row: ApplicationDetail) => row.tier },
    { label: 'Lifecycle', render: (row: ApplicationDetail) => applicationChip(row.lifecycle, 'lifecycle') },
    { label: 'Health', numeric: true, render: (row: ApplicationDetail) => row.healthScore },
    { label: 'Automation %', numeric: true, render: (row: ApplicationDetail) => row.automationCoverage },
    { label: 'Open Critical Defects', numeric: true, render: (row: ApplicationDetail) => row.openCriticalDefects },
    { label: 'Risk', render: (row: ApplicationDetail) => applicationChip(row.risk, 'risk') },
  ];
  return (
    <>
      <div className="flex flex-wrap items-center justify-between gap-4">
        <h1>Applications</h1>
        {canCreate && (
          <Link to="/applications/new"
            className="inline-flex items-center h-10 px-4 rounded bg-deep-forest-teal text-on-primary text-label-md no-underline">
            New application
          </Link>
        )}
      </div>
      <p className="muted">Explore maintained ownership, health, automation, and risk across your permitted applications.</p>
      {location.state?.message && <p role="status" className="feedback">{location.state.message}</p>}
      <div className="bg-surface-tint rounded-lg p-4 flex flex-wrap gap-4 mb-4">
        <Field id="application-search" label="Search by name">
          <input id="application-search" maxLength={200} value={params.get('search') ?? ''}
            onChange={event => filter('search', event.target.value)} />
        </Field>
        <Field id="application-portfolio" label="Portfolio">
          <select id="application-portfolio" value={params.get('portfolioId') ?? ''}
            onChange={event => filter('portfolioId', event.target.value)}>
            <option value="">All portfolios</option>
            {resource.data?.portfolios.map(row => <option key={row.id} value={row.id}>{row.name}</option>)}
          </select>
        </Field>
        {(['criticality', 'risk', 'lifecycle'] as const).map(key => (
          <Field key={key} id={`application-${key}`} label={key[0].toUpperCase() + key.slice(1)}>
            <select id={`application-${key}`} value={params.get(key) ?? ''} onChange={event => filter(key, event.target.value)}>
              <option value="">All {key}</option>
              {(resource.data?.[{ criticality: 'criticalities', risk: 'risks', lifecycle: 'lifecycles' }[key] as
                'criticalities' | 'risks' | 'lifecycles'] ?? []).map(value => <option key={value}>{value}</option>)}
            </select>
          </Field>
        ))}
        <button className="secondary" onClick={() => setParams({})}>Clear filters</button>
        {user.role !== 'Read Only' && user.permissions.includes('export') && (
          <button disabled={pending || resource.loading || Boolean(resource.error)} onClick={download}>
            {pending ? 'Downloading…' : 'Download CSV'}
          </button>
        )}
      </div>
      {error && <p role="alert" className="error">{error}</p>}
      {resource.loading ? <div className="card bg-surface-container" role="status">Loading applications…</div> : resource.error ? (
        <div className="card">
          <p role="alert" className="error">{resource.error}</p>
          <button className="secondary" onClick={resource.reload}>Retry</button>
        </div>
      ) : resource.data && (
        <DataTable rows={resource.data.items} columns={columns} rowKey={row => row.id}
          page={resource.data.page} pageSize={resource.data.page_size} total={resource.data.total}
          onPage={page => { const next = new URLSearchParams(params); next.set('page', String(page)); setParams(next); }} />
      )}
    </>
  );
}
